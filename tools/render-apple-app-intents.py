#!/usr/bin/env python3
"""Render data/apple-app-intents.json (from dump-toolkit-registry.py) into a markdown reference.

usage: render-apple-app-intents.py IN.json OUT.md
"""
import json
import sys
from collections import defaultdict


def main(argv):
    doc = json.load(open(argv[1]))
    actions = doc["actions"]
    by_app = defaultdict(list)
    for ident, t in sorted(actions.items()):
        by_app[(t.get("app") or {}).get("name") or "?"].append(t)
    lines = ["# Apple app actions", "",
             f"The {len(actions):,} App Intents actions of {len(by_app)} Apple apps and system components, as the Shortcuts",
             "app indexes them ([how](extraction.md)). `Shortcut.action()` adds each one's `AppIntentDescriptor`.",
             "Generated by `tools/render-apple-app-intents.py`; do not edit.", ""]
    prov = doc.get("provenance") or {}
    if prov.get("source"):
        lines[-1:] = ["", f"Read from `{prov['source']}`, indexed on build {prov.get('osVersion')} (see `data/provenance.json`).", ""]
    for app in sorted(by_app):
        ts = by_app[app]
        bundle = (ts[0].get("app") or {}).get("bundleIdentifier")
        lines += [f"## {app} (`{bundle}`)", ""]
        for t in ts:
            lines += [f"### {t.get('name') or t['identifier']}", "", f"`actions.{t['key']}` · `{t['identifier']}`" if t.get("key") else f"`{t['identifier']}`"]
            if t.get("description"):
                lines.append(f"  \n{t['description']}")
            name, outs = t.get("outputName") or "", [o for o in t.get("outputTypes") or [] if o != "none"]
            if name or outs:
                lines.append("  \nOutput: " + (f"{name} (`{', '.join(outs)}`)" if name and outs else name or f"`{', '.join(outs)}`"))
            lines.append("")
            if t.get("parameters"):
                lines += ["| Key | Name | Kind | Type |", "|---|---|---|---|"]
                for p in t["parameters"]:
                    ty = p.get("type") or {}
                    if ty.get("kind") == "primitive":
                        tdesc = ty.get("primitive")
                    elif ty.get("kind") == "enum":
                        tdesc = "enum: " + ", ".join(f"`{c['id']}`" for c in ty.get("cases", [])[:12]) + (" …" if len(ty.get("cases", [])) > 12 else "")
                    else:
                        tdesc = f"{ty.get('kind')} {ty.get('name') or ''}".strip()
                    lines.append(f"| `{p['key']}` | {p.get('name') or ''} | {p.get('kind')} | {tdesc} |")
                lines.append("")
    open(argv[2], "w").write("\n".join(lines))
    print(f"{len(actions)} actions from {len(by_app)} apps -> {argv[2]}")


if __name__ == "__main__":
    main(sys.argv)
